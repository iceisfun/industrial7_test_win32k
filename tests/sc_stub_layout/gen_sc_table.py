#!/usr/bin/env python3
# Regenerates sc_table.c from tools/win32u_syscalls.json and tools/win32u_exports.json
# (19041 reference corpus). Run from anywhere:  python3 -I gen_sc_table.py
import json, os
here = os.path.dirname(os.path.abspath(__file__))
tools = os.path.join(here, '..', '..', 'tools')
sc = sorted(json.load(open(os.path.join(tools, 'win32u_syscalls.json'))), key=lambda x: x['number'])
ex = json.load(open(os.path.join(tools, 'win32u_exports.json')))
ords = {e['name']: e['ordinal'] for e in ex}
byord = sorted(ex, key=lambda e: e['ordinal'])
with open(os.path.join(here, 'sc_table.c'), 'w') as f:
    f.write('/* GENERATED by gen_sc_table.py - win32u.dll 19041 syscall table (number order) */\n#include "sc_common.h"\n')
    f.write('const struct sc_entry sc_tab[SC_COUNT] = {\n')
    for x in sc:
        f.write('  { "%s", %d, 0x%x, %d },\n' % (x['name'], x['number'], x['rva'], ords[x['name']]))
    f.write('};\n')
    f.write('const char *const sc_export_names[SC_EXPORTS] = {\n')
    for e in byord:
        f.write('  "%s",\n' % e['name'])
    f.write('};\n')
    f.write('const unsigned sc_export_rva[SC_EXPORTS] = {\n')
    for e in byord:
        f.write('  0x%x,\n' % e['rva'])
    f.write('};\n')
